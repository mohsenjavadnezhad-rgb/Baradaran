<?php
/* =====================================================================
   لایهٔ مالیات — اختیاری، درصدی و مستقل روی هر محصول
   ---------------------------------------------------------------------
   خواستهٔ مدیر: «اگه خواست در موقع ورود کالا بتونه توی قیمت‌گذاری اونو فعال
   و درصد رو مشخص کنه». پس هیچ تنظیمِ سراسری‌ای در کار نیست — هر محصول
   می‌تواند مالیاتِ خودش را داشته باشد یا نداشته باشد.
   مالیات به مبلغِ قابل‌پرداخت (سبد/تسویه/سفارش) اضافه می‌شود و روی فاکتور هم
   به‌صورت ردیفِ جدا نشان داده می‌شود؛ برای این‌که فاکتورِ سفارش‌های قدیمی با
   تغییرِ بعدیِ درصدِ محصول عوض نشود، درصد و مبلغِ مالیات در لحظهٔ ثبت سفارش
   روی خودِ order_items هم ذخیره می‌شود (همان الگوی قیمتِ لحظه‌ای).
   ===================================================================== */

/* آیا ستون‌های مالیات ساخته شده‌اند؟ (migrate-tax.php) */
function taxReady() {
    return dbHasColumn('products', 'tax_enabled');
}

/* آیا ستون‌های مالیات روی order_items هم ساخته شده‌اند؟ */
function taxItemsReady() {
    return taxReady() && dbHasColumn('order_items', 'tax_amount');
}

/* درصدِ مالیاتِ یک محصول — فقط اگر خودِ محصول تیکِ مالیات را داشته باشد */
function productTaxPercent(array $product) {
    if (!taxReady()) return 0.0;
    if (empty($product['tax_enabled'])) return 0.0;
    $p = (float)($product['tax_percent'] ?? 0);
    return $p > 0 ? $p : 0.0;
}

/* مبلغِ مالیاتِ یک ردیف بر اساس جمعِ آن ردیف و درصد — همیشه به تومانِ صحیح گرد می‌شود */
function taxAmountFor($subtotal, $percent) {
    $percent = (float)$percent;
    if ($percent <= 0) return 0;
    return (int)round(((float)$subtotal * $percent) / 100);
}

/* جمعِ مالیاتِ چند ردیف (سبد یا اقلامِ سفارش) — هر ردیف باید کلید tax_amount داشته باشد */
function itemsTaxTotal(array $items) {
    $t = 0;
    foreach ($items as $it) $t += (int)($it['tax_amount'] ?? 0);
    return $t;
}
